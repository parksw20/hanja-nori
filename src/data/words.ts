/** 급수 사다리 — 아래에서 위로. 이 순서가 해금 순서이자 누계 순서다. */
export const LADDER: readonly GradeId[] = ['8', '7II', '7', '6II', '6', '5II', '5', '4II', '4']

export const NEW_BY_GRADE: Readonly<Record<GradeId, Hanja[]>> = {
  '8': HANJA_8,
  '7II': HANJA_7II,
  '7': HANJA_7,
  '6II': HANJA_6II,
  '6': HANJA_6,
  '5II': HANJA_5II,
  '5': HANJA_5,
  '4II': HANJA_4II,
  '4': HANJA_4,
}

/** 그 급수까지의 **누계** 배정한자 (8급 50 → 6급 300) */
export function cumulative(grade: GradeId): Hanja[] {
  const upto = LADDER.slice(0, LADDER.indexOf(grade) + 1)
  return upto.flatMap((g) => NEW_BY_GRADE[g])
}

export const ALL_HANJA: Hanja[] = cumulative(LADDER[LADDER.length - 1])
export const HANJA_BY_CHAR: ReadonlyMap<string, Hanja> = new Map(ALL_HANJA.map((h) => [h.char, h]))

const GRADE_RANK = new Map(LADDER.map((g, i) => [g, i]))

/** 낱말이 어느 급수부터 낼 수 있는지 = 구성 글자 중 가장 높은 급수. 손으로 적지 않고 계산한다. */
export function wordGrade(word: string): GradeId {
  let rank = 0
  for (const c of word) {
    const h = HANJA_BY_CHAR.get(c)
    if (!h) throw new Error(`배정한자에 없는 글자가 낱말에 있다: ${c} (${word})`)
    rank = Math.max(rank, GRADE_RANK.get(h.grade) ?? 0)
  }
  return LADDER[rank]
}

/** '家 집 가' 처럼 훈음을 한 덩어리로 */
export function hunEumOf(char: string): string {
  const h = HANJA_BY_CHAR.get(char)
  return h ? `${h.hun} ${h.eum}` : char
}

