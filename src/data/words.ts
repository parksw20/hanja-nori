export const ALL_WORDS: Word[] = [
  ...WORDS_8,
  ...RAW.map((row) => {
    const [word, reading, meaning] = row.split('|')
    return { word, reading, meaning, grade: wordGrade(word) }
  }),
]

/** 그 급수까지 낼 수 있는 낱말 (누계) */
export function wordsUpTo(grade: GradeId): Word[] {
  const max = GRADE_RANK.get(grade) ?? 0
  return ALL_WORDS.filter((w) => (GRADE_RANK.get(w.grade) ?? 0) <= max)
}
