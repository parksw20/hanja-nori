/** 그 급수까지 낼 수 있는 것만 추린다 */
export function upTo<T extends { grade: GradeId }>(items: T[], grade: GradeId): T[] {
  const max = RANK.get(grade) ?? 0
  return items.filter((i) => (RANK.get(i.grade) ?? 0) <= max)
}
