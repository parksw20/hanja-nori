import type { GradeId } from './types'
import { HANJA_BY_CHAR, LADDER } from './words'

/**
 * 반의어(상대어)·유의어(동의어)·완성형(성어) 데이터.
 *
 * 이 셋만 손으로 넣는다 — 나머지 출제 유형(독음·훈음·필순·뜻풀이·한자쓰기·동음이의어)은
 * 배정한자와 한자어에서 **계산해서** 만든다.
 *
 * 급수는 구성 글자에서 계산한다. 손으로 적으면 틀린다.
 */

const RANK = new Map(LADDER.map((g, i) => [g, i]))

function gradeOf(chars: string): GradeId {
  let rank = 0
  for (const c of chars) {
    const h = HANJA_BY_CHAR.get(c)
    if (!h) throw new Error(`배정한자에 없는 글자: ${c} (${chars})`)
    rank = Math.max(rank, RANK.get(h.grade) ?? 0)
  }
  return LADDER[rank]
}

export interface Pair {
  a: string
  b: string
  grade: GradeId
  /** 화면에 띄울 설명 */
  note: string
}

export interface Idiom {
  /** 성어 네 글자 */
  text: string
  reading: string
  meaning: string
  grade: GradeId
}

function pairs(rows: string[]): Pair[] {
  return rows.map((row) => {
    const [ab, note] = row.split('|')
    const [a, b] = [...ab]
    return { a, b, grade: gradeOf(ab), note }
  })
}

