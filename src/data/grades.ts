function parse(table: string, grade: GradeId): Hanja[] {
  return table.split('|').map((row) => {
    const parts = row.trim().split(' ')
    if (parts.length !== 3) throw new Error(`배정한자 형식이 깨졌다: "${row}" (급수 ${grade})`)
    const [char, hun, rawEum] = parts
    // 음 뒤의 표시가 장단음 — ':' 장음, '?' 장단 혼용, 없으면 단음
    const tone = rawEum.endsWith(':') ? 'long' : rawEum.endsWith('?') ? 'both' : undefined
    const eum = rawEum.replace(/[:?]$/, '')
    return tone ? { char, hun, eum, grade, tone } : { char, hun, eum, grade }
  })
}

